# There are several data types in python. 
# Integer(int)
a = 10; b = -5
#float(double)
c = 3.14; d = -0.001
#string(str)
e = "Hello, World!"
#boolean(bool)
f = True; g = False
#list
h = [1, 2, 3, 4, 5]
#tuple
i = (10, 20, 30)
#set
j = {1, 2, 3, 4, 5} 
#dictionary(dict)
k = {"name": "Alice", "age": 25}
#complex
l = 2 + 3j
#NoneType
m = None
# Printing the data types
print(type(a), type(b), type(c), type(d), type(e), type(f), type(g), type(h), type(i), type(j), type(k), type(l), type(m))