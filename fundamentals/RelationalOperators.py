#We'll talk about relational operators. 

a = int(input("Enter a no. : "))
b = int(input("Enter another no. : "))

#NOTE: ALL THESE OPERATORS WILL GIVE O/P IN BOOLEAN VALUES. 

#">" greater than 
print(a>b)

#"<" lesser than
print(a<b)

#">=" greater than equal to 
print(a>=b)

#"<=" lesser than equal to 
print(a<=b)

#"==" equal to
print(a==b)

#"!=" not equal to 
print(a!=b)


